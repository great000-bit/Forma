// Generates templates/library.ts from the research docs. Run once per research
// update: `node scripts/extract-templates.mjs > /tmp/tpl.json && node scripts/build-template-library.mjs`.
// The output is committed and reviewed like any other code.
import { readFileSync, writeFileSync } from "node:fs";
const data = JSON.parse(readFileSync("/tmp/tpl.json", "utf8"));
const extra = JSON.parse(readFileSync("scripts/concepts-extra.json", "utf8"));
const slug = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const tidy = (c) => { c = c.replace(/\s+/g, " ").trim(); c = c[0].toUpperCase() + c.slice(1); return /[.!?]$/.test(c) ? c : c + "."; };
const has = (re, s) => re.test(s.toLowerCase());

function pick(name, concept) {
  const s = `${name} ${concept}`;
  const n = name.toLowerCase();
  let preset = "stack";
  if (has(/terminal|console|shell|test-runner/, s)) preset = "terminal";
  else if (has(/\bdark\b|night|cinematic|noir|near-black/, s)) preset = "dark-editorial";
  else if (/^one page|minimal|^minimal/.test(n)) preset = "centered";
  else if (has(/sidebar|sticky|left nav|docs site|matrix/, s)) preset = "sidebar";
  else if (has(/index|table|archive|text-only|text-led|reading list|résumé|resume|recruiter|feed|\blog\b|scoreboard|list\b|checklist|certs|certifications/, s)) preset = "index";
  else if (has(/wall|grid|gallery|full-bleed|full-screen|edge-to-edge|render|photo|reel|frames?\b|screenshots|poster|cover|loops|captures|tiles/, s)) preset = "gallery";
  else if (has(/case|story|in depth|hero|trailer|leads|first screen|fills|one app|one product/, s)) preset = "feature";
  else if (has(/portrait|serif|editorial|paper|book|letterhead|masthead/, s)) preset = "split";
  const theme = {};
  if (preset === "terminal") Object.assign(theme, { mode: "dark", font: "mono" });
  if (preset === "dark-editorial") theme.mode = "dark";
  if (!theme.font && has(/serif|editorial|story|writer|narrative|book|paper|long-form|essay|letter/, s)) theme.font = "serif";
  if (!theme.font && has(/code|repo|mono|sql|notebook|firmware|query|rules|hash|snippet|schematic|blueprint/, s)) theme.font = "mono";
  if (has(/naija|lagos|local|africa|naira|market\b|whatsapp|nigerian/, s)) theme.accent = "#1F9D6B";
  else if (has(/\bbright|\bloud\b|arcade|colour block|bold, warm|playful|pixel/, s)) theme.accent = "#E8590C";
  else if (has(/corporate|navy|conservative|formal|bank|consult/, s)) theme.accent = "#1E3A8A";
  else if (has(/studio|freelance|services|packages|booking/, s)) theme.accent = "#0F766E";
  return { preset, theme };
}

const out = [];
const stats = {};
const ROTATE = ["split", "sidebar", "feature", "gallery", "index", "stack"];
const PALETTE = ["#0F766E", "#B4235A", "#1E3A8A", "#C2410C", "#7C3AED", "#0369A1", "#A16207", "#15803D"];
const FONTS = ["sans", "serif", "mono"];
const key = (p, t) => [p, t.mode ?? "light", t.font ?? "sans", t.accent ?? "default"].join("|");
for (const [niche, rows] of Object.entries(data)) {
  const seen = new Set();
  const combos = new Set();
  const used = {};
  let r = 0;
  stats[niche] = {};
  for (const [name, c] of rows) {
    const concept = c || extra[niche]?.[name];
    if (!concept) throw new Error(`No concept for ${niche}/${name}`);
    let id = slug(name);
    while (seen.has(id)) id += "-2";
    seen.add(id);
    let { preset, theme } = pick(name, concept);
    // Unsignalled templates spread across presets so a niche never has a
    // pile of identical-looking stacks.
    if (preset === "stack" && (used.stack ?? 0) >= 3) {
      preset = [...ROTATE].sort((a, b) => (used[a] ?? 0) - (used[b] ?? 0))[0];
    }
    used[preset] = (used[preset] ?? 0) + 1;
    // Every template in a niche must look different: vary accent, then font.
    let tries = 0;
    while (combos.has(key(preset, theme))) {
      if (tries < PALETTE.length) theme = { ...theme, accent: PALETTE[(r++) % PALETTE.length] };
      else theme = { ...theme, font: FONTS[tries % 3] };
      tries++;
    }
    combos.add(key(preset, theme));
    stats[niche][preset] = (stats[niche][preset] ?? 0) + 1;
    out.push({ id: `${niche}/${id}`, niche, name, concept: tidy(concept), preset, ...(Object.keys(theme).length ? { theme } : {}) });
  }
}
const body = out.map((t) => "  " + JSON.stringify(t)).join(",\n");
writeFileSync(
  "templates/library.ts",
  `// Generated by scripts/build-template-library.mjs from docs/research. Edit the\n// research docs or the script, then regenerate. Concepts are original.\nimport type { TemplateDef } from "./catalog";\n\nexport const LIBRARY: TemplateDef[] = [\n${body},\n];\n`,
);
for (const [n, s] of Object.entries(stats)) console.log(n.padEnd(26), Object.keys(s).length, JSON.stringify(s));
console.log("total", out.length);
